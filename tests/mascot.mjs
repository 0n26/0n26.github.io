import { JSDOM } from 'jsdom';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, unlinkSync, existsSync } from 'node:fs';
import { transform } from 'esbuild';
import React, { act } from 'react';
const dom = new JSDOM('<div id="root"></div>', { pretendToBeVisual: true });
globalThis.window = dom.window; globalThis.document = dom.window.document;
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const mediaListeners = new Set();
const media = { matches: false, addEventListener: (_, fn) => mediaListeners.add(fn), removeEventListener: (_, fn) => mediaListeners.delete(fn) };
window.matchMedia = () => media;
const intervals = new Map(), timeouts = new Map(); let sequence = 0;
window.setInterval = (fn, ms) => { const id = ++sequence; intervals.set(id, { fn, ms }); return id; };
window.clearInterval = id => intervals.delete(id);
window.setTimeout = (fn, ms) => { const id = ++sequence; timeouts.set(id, { fn, ms }); return id; };
window.clearTimeout = id => timeouts.delete(id);
const listeners = new Map();
const add = window.addEventListener.bind(window), remove = window.removeEventListener.bind(window);
window.addEventListener = (type, fn, ...rest) => { if (type === 'resize') listeners.set(fn,type); add(type,fn,...rest); };
window.removeEventListener = (type, fn, ...rest) => { listeners.delete(fn); remove(type,fn,...rest); };
const file = new URL('../src/.mascot-test.mjs', import.meta.url);
const source = readFileSync(new URL('../src/Mascot.jsx', import.meta.url), 'utf8').replace("import './mascot.css';",'').replaceAll('import.meta.env.BASE_URL',"'/'");
writeFileSync(file, (await transform(source,{loader:'jsx',format:'esm'})).code);
try {
 const {default:Mascot} = await import(file.href);
 const {createRoot} = await import('react-dom/client');
 const root = createRoot(document.querySelector('#root'));
 await act(() => root.render(React.createElement(React.StrictMode,null,React.createElement(Mascot))));
 const robot = () => document.querySelector('.mascot');
 const button = name => [...document.querySelectorAll('button')].find(b=>b.getAttribute('aria-label')?.includes(name));
 const click = async name => { await act(()=>button(name).click()); };
 assert.equal(intervals.size,2,'StrictMode leaves only two autonomous timers');
 assert.equal(mediaListeners.size,1); assert.equal(listeners.size,1);
 assert.equal(robot().dataset.face,'idle');
 const originalRandom = Math.random; Math.random = () => .1;
 await act(()=>[...intervals.values()].find(t=>t.ms===12000).fn());
 assert.equal(robot().dataset.face,'walk');
 const startX=parseFloat(robot().style.left);
 await act(()=>[...intervals.values()].find(t=>t.ms===80).fn());
 assert.ok(parseFloat(robot().style.left)<startX,'walking changes position');
 Math.random=originalRandom;
 await click('Нажмите'); assert.equal(robot().dataset.face,'happy');
 await click('Приостановить'); assert.equal(robot().dataset.paused,'true'); assert.equal(intervals.size,0); assert.equal(timeouts.size,0);
 await click('Продолжить'); assert.equal(intervals.size,2);
 await act(()=>button('Нажмите').focus()); assert.equal(intervals.size,0,'keyboard focus stops autonomous movement');
 await act(()=>button('Нажмите').blur()); assert.equal(intervals.size,2);
 await act(()=>robot().dispatchEvent(new window.MouseEvent('mouseover',{bubbles:true})));
 assert.equal(intervals.size,0,'hover pauses');
 await act(()=>robot().dispatchEvent(new window.MouseEvent('mouseout',{bubbles:true,relatedTarget:document.body})));
 assert.equal(intervals.size,2);
 await click('Скрыть'); assert.equal(robot(),null); assert.equal(intervals.size,0); assert.ok(button('Показать'));
 await click('Показать'); assert.ok(robot()); assert.equal(intervals.size,2);
 window.innerWidth=320; await act(()=>window.dispatchEvent(new window.Event('resize')));
 assert.ok(parseFloat(robot().style.left)<=168,'bounds clamp on narrow resize');
 await act(()=>{ media.matches=true; mediaListeners.forEach(fn=>fn()); });
 assert.equal(intervals.size,0,'reduced motion disables all autonomous timers'); assert.equal(robot().dataset.face,'idle');
 await click('Нажмите'); assert.equal(robot().dataset.face,'curious','explicit still expression remains available');
 await act(()=>root.render(React.createElement(React.StrictMode,null,React.createElement(Mascot,{projectSignal:1}))));
 assert.equal(robot().dataset.face,'curious');
 await act(()=>root.unmount());
 assert.equal(intervals.size,0); assert.equal(timeouts.size,0); assert.equal(mediaListeners.size,0); assert.equal(listeners.size,0);
 for(const state of ['idle','blink','happy','curious','surprised','sleepy','walk','wave']) {
   const path=new URL(`../public/assets/mascot/${state}.svg`,import.meta.url);
   assert.ok(existsSync(path),`${state} SVG exists`); assert.match(readFileSync(path,'utf8'), /viewBox="0 0 96 112"/);
 }
 console.log('PASS mascot: StrictMode timers/listener cleanup, tap expressions, pause/resume, focus/hover, hide/restore, resize bounds, reduced-motion, project reaction, all SVG states.');
} finally { unlinkSync(file); dom.window.close(); }
